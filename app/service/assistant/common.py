def chunks(text: str):
    for i in range(0, len(text), CHUNK):
        yield text[i:i + CHUNK]


def hhmm(onset: str | None) -> str | None:
    return onset[11:16] if onset and len(onset) >= 16 else None


def act_phrase(dispatch: dict | None) -> str:
    if not dispatch:
        return "暫可觀察"
    act, bikes = dispatch.get("action"), dispatch.get("bikes")
    if act in ACT_WORD and bikes is not None:
        return f"{ACT_WORD[act]} {bikes} 台"
    return "暫可觀察"


def open_action(item: dict) -> dict:
    return {"label": f"開啟 {item['name']}",
            "type": "select_station", "value": item["station_uid"]}
